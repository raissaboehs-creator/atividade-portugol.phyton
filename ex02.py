# Objetivo: Ler dois números e mostrar soma, subtração e multipliação

num1 = int(input("Digite o seu primeiro número: ")) #Campo para digitar os números.
num2 = int(input("Digite o seu segundo número: ")) 

#
soma = num1 + num2 
sub = num1 - num2 
mult = num1 * num2 

print("O resultado da soma é", soma) #exibe o resultado da soma
print("O resultado da subtração é", sub) #exibe o resultado da subtração
print("O resultado da multiplicação é", mult) #exibe o resultado da multiplicação